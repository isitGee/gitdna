// Extracts official brand SVG path data (simple-icons, CC0) for the technologies
// gitDNA detects, and emits a compact TypeScript module. Run: npm run gen:logos
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const SLUGS = [
  'javascript','typescript','html5','css','sass','json','yaml','markdown','toml','python','go','rust',
  'ruby','php','kotlin','swift','c','cplusplus','scala','elixir','dart','lua','r','zig',
  'gnubash','react','vuedotjs','svelte','angular','nextdotjs','nuxt','astro','express',
  'fastify','gatsby','django','flask','flutter','jekyll','nodedotjs','docker','githubactions','githubpages',
  'vite','webpack','tailwindcss','redux','reactrouter','axios','threedotjs','d3','chartdotjs',
  'framer','jest','vitest','mongoose','prisma','sequelize','postgresql','mysql','redis','socketdotio',
  'stripe','firebase','supabase','numpy','pandas','scikitlearn','pytorch','tensorflow','keras',
  'celery','sqlalchemy','streamlit','pytest','jupyter','gradle','apachemaven','cmake',
  'openjdk','mui','testinglibrary','git',
]

const manifest = JSON.parse(readFileSync('node_modules/simple-icons/data/simple-icons.json', 'utf8'))
const bySlug = new Map(manifest.map((e) => [e.slug, e]))

const entries = []
const missing = []
for (const slug of SLUGS) {
  const svgPath = `node_modules/simple-icons/icons/${slug}.svg`
  const meta = bySlug.get(slug)
  if (!meta || !existsSync(svgPath)) { missing.push(slug); continue }
  const svg = readFileSync(svgPath, 'utf8')
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (paths.length === 0) { missing.push(slug); continue }
  entries.push({ title: meta.title, slug, hex: meta.hex, d: paths.join(' ') })
}

const out = `// Generated by scripts/generate-brand-logos.mjs — do not edit by hand.
// Brand marks and colors from simple-icons (CC0). Regenerate with: npm run gen:logos
export interface BrandLogo { title: string; slug: string; hex: string; d: string }

export const BRAND_LOGOS: Record<string, BrandLogo> = {
${entries.map((e) => `  ${JSON.stringify(e.slug)}: ${JSON.stringify(e)},`).join('\n')}
}
`
writeFileSync('src/components/shared/brandLogos.ts', out)
console.log(`wrote ${entries.length} brand logos (${(out.length / 1024).toFixed(0)} KB source)`)
if (missing.length) console.log('missing (will use fallback glyph):', missing.join(', '))
